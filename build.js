// Bundles the pure-JS modules + the Affinity glue into one Affinity script:
//   node build.js   →   dist/ContentAwareScale.js
'use strict';
const fs = require('fs');
const path = require('path');

const root = __dirname;
const read = f => fs.readFileSync(path.join(root, 'src', f), 'utf8');
const strip = code => code.split('// @@NODE_EXPORT@@')[0].replace(/^'use strict';\s*/m, '');

// Pure modules first (each defines one global), then the Affinity glue.
const modules = ['seamcarve.js', 'loading-overlay.js'].map(f => strip(read(f)));
const glue = read('affinity-main.js').replace(/^'use strict';\s*/m, '');

const out = `// Content-Aware Scale for Affinity — generated by build.js, do not edit.\n'use strict';\n\n${modules.join('\n')}\n${glue}`;
fs.mkdirSync(path.join(root, 'dist'), { recursive: true });
fs.writeFileSync(path.join(root, 'dist', 'ContentAwareScale.js'), out);
console.log('wrote dist/ContentAwareScale.js');
